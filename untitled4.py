import threading
import queue
import time
import random
trabajos = queue.Queue()
for i in range(1, 25):
    tamano = random.randint(1, 5)
    trabajos.put((i, tamano))
nombres = ["Rosmery", "Neyda", "Maricel", "Alex"]
lock = threading.Lock()
resultados = {
    nombre: {"cantidad": 0, "tamano": 0, "ids": []}
    for nombre in nombres
}
documentos_procesados = []
def trabajador(nombre):
    for i in range(6):
        try:
            documento, tamano = trabajos.get_nowait()
        except queue.Empty:
            break
        print(nombre, "procesa documento", documento)
        time.sleep(random.uniform(0.1, 0.5) * tamano)
        with lock:
            resultados[nombre]["cantidad"] += 1
            resultados[nombre]["tamano"] += tamano
            resultados[nombre]["ids"].append(documento)
            documentos_procesados.append(documento)
        print(nombre, "termino documento", documento)
        trabajos.task_done()
hilos = []
inicio = time.perf_counter()
for nombre in nombres:
    hilo = threading.Thread(
        target=trabajador,
        args=(nombre,)
    )
    hilos.append(hilo)
for hilo in hilos:
    hilo.start()
for hilo in hilos:
    hilo.join()
fin = time.perf_counter()
print("\n=RESUMEN FINAL")
total = 0
for nombre in nombres:
    datos = resultados[nombre]
    print("\nTrabajador:", nombre)
    print("Documentos:", datos["cantidad"])
    print("IDs:", sorted(datos["ids"]))
    print("Tamano acumulado:", datos["tamano"], "MB")
    total += datos["cantidad"]
ids_unicos = len(documentos_procesados) == len(set(documentos_procesados))
ids_correctos = sorted(documentos_procesados) == list(range(1, 25))
seis_cada_uno = all(
    resultados[n]["cantidad"] == 6
    for n in nombres
)
finalizados = all(not h.is_alive() for h in hilos)
print("\n=COMPROBACIONES")
print("Total procesado:", total)
print("Documentos pendientes:", trabajos.qsize())
print("IDs sin repetir:", ids_unicos)
print("Documentos del 1 al 24:", ids_correctos)
print("Seis documentos por trabajador:", seis_cada_uno)
print("Cuatro hilos finalizados:", finalizados)
print("Tiempo total:", round(fin - inicio, 3), "segundos")